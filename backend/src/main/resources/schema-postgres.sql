-- Todo List Management System — PostgreSQL schema (production on Render).
-- Only needed if you want explicit DDL; spring.jpa.hibernate.ddl-auto=update
-- in application-prod.properties creates these tables automatically.
-- Run with: psql "$DATABASE_URL" -f schema-postgres.sql

CREATE TABLE IF NOT EXISTS users (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100) NOT NULL,
    email      VARCHAR(150) NOT NULL UNIQUE,
    password   VARCHAR(255) NOT NULL,
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS tasks (
    id                  BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title               VARCHAR(200) NOT NULL,
    description         TEXT         NULL,
    due_date            DATE         NULL,
    priority            VARCHAR(20)  NOT NULL DEFAULT 'MEDIUM',
    status              VARCHAR(30)  NOT NULL DEFAULT 'TODO',
    user_id             BIGINT       NOT NULL,
    last_reminder_sent_at TIMESTAMP  NULL,
    created_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_tasks_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_tasks_user_id ON tasks (user_id);
CREATE INDEX IF NOT EXISTS idx_tasks_status ON tasks (status);
CREATE INDEX IF NOT EXISTS idx_tasks_priority ON tasks (priority);
CREATE INDEX IF NOT EXISTS idx_tasks_due_date ON tasks (due_date);

